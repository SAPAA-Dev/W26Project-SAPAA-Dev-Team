-- #75: create the user model approved in #116 (see docs/user-model.md).
-- `people` has one row for each person with a login. `site_stewards` links one steward to
-- each site. A human runs this same file in the Supabase dashboard for production, after
-- 20261003000000_remove_w26_prefix.sql. Every step is safe to run twice.

create table if not exists public.people (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users (id) on delete set null,
  display_name text not null check (length(trim(display_name)) > 0 and length(trim(display_name)) < 30),
  skills text[] not null default '{}',
  focus_areas text[] not null default '{}',
  activity_points integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- site_id is the primary key, so a site has one steward and a new assignment replaces the old one (3.0.2 AT2).
create table if not exists public.site_stewards (
  site_id bigint primary key references public.sites_pa (id) on delete cascade,
  steward_id bigint not null references public.people (id) on delete cascade,
  assigned_by uuid references auth.users (id) on delete set null,
  assigned_at timestamptz not null default now()
);

create index if not exists site_stewards_steward_id_idx on public.site_stewards (steward_id);

alter table public.people enable row level security;
alter table public.site_stewards enable row level security;

drop policy if exists "people are visible to signed-in users" on public.people;
create policy "people are visible to signed-in users"
  on public.people for select to authenticated using (true);

drop policy if exists "users update only their own person record" on public.people;
create policy "users update only their own person record"
  on public.people for update to authenticated
  using (auth_user_id = (select auth.uid())) with check (auth_user_id = (select auth.uid()));

drop policy if exists "site stewards are visible to signed-in users" on public.site_stewards;
create policy "site stewards are visible to signed-in users"
  on public.site_stewards for select to authenticated using (true);
-- No insert, update or delete policy: only admin server actions write site_stewards.

-- RLS limits which rows a user can change. These grants limit the columns: a user can edit
-- only their profile fields, not activity_points (1.0.5), id, auth_user_id or the timestamps.
revoke all on public.people, public.site_stewards from anon;
revoke insert, update, delete on public.people, public.site_stewards from authenticated;
grant update (display_name, skills, focus_areas) on public.people to authenticated;

create or replace function public.set_updated_at() returns trigger
  language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists people_set_updated_at on public.people;
create trigger people_set_updated_at
  before update on public.people
  for each row execute function public.set_updated_at();

-- Make a person record when a user signs up.
create or replace function public.create_person_for_new_user() returns trigger
  language plpgsql security definer set search_path = '' as $$
begin
  -- left(..., 29) keeps long names inside the display_name check. If the check failed here,
  -- the sign-up itself would fail.
  insert into public.people (auth_user_id, display_name)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
                  nullif(split_part(new.email, '@', 1), ''), 'New user'), 29)
  );
  return new;
end;
$$;

revoke execute on function public.create_person_for_new_user() from public, anon, authenticated;

-- Not the Supabase template name (on_auth_user_created), so this never replaces another trigger.
drop trigger if exists create_person_on_signup on auth.users;
create trigger create_person_on_signup
  after insert on auth.users
  for each row execute function public.create_person_for_new_user();

-- Give every existing user a person record.
insert into public.people (auth_user_id, display_name)
select id,
       left(coalesce(nullif(trim(raw_user_meta_data ->> 'full_name'), ''),
                     nullif(split_part(email, '@', 1), ''), 'New user'), 29)
from auth.users
on conflict (auth_user_id) do nothing;

notify pgrst, 'reload schema';
