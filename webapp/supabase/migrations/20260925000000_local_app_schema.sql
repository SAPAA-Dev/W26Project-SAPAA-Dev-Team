create or replace function public.get_naturalness_distribution()
returns table (naturalness_score text, count bigint)
language sql
stable
security invoker
set search_path = public
as $$
  select answers.obs_value, count(*)
  from public."W26_answers" as answers
  join public."W26_questions" as questions on questions.id = answers.question_id
  join public."W26_form_responses" as responses on responses.id = answers.response_id
  where questions."question key" = 'Q31_Naturalness'
    and responses.is_active
    and answers.obs_value is not null
  group by answers.obs_value
  order by answers.obs_value;
$$;

create or replace function public.get_top_sites_distribution()
returns table (namesite text, count bigint)
language sql
stable
security invoker
set search_path = public
as $$
  select sites.namesite, count(*)
  from public."W26_form_responses" as responses
  join public."W26_sites-pa" as sites on sites.id = responses.site_id
  where responses.is_active
  group by sites.namesite
  order by count(*) desc, sites.namesite
  limit 5;
$$;

grant execute on function public.get_naturalness_distribution() to service_role;
grant execute on function public.get_top_sites_distribution() to service_role;
