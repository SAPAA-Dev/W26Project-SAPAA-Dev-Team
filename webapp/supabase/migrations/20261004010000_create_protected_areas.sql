-- US 2.0.6 / 6.0.1: protected area boundaries from Alberta Open Data (KML converted to GeoJSON).
-- The map reads label_point for pins (Sprint 2) and geometry for boundaries (Sprint 3).
-- An import script fills this table and is rerun when Frank sends his full data set, so rows
-- are matched on global_id, which stays the same between exports (objectid can change).
-- A human runs this same file in the Supabase dashboard for production, after
-- 20261003000000_remove_w26_prefix.sql (site_id references sites_pa). Safe to run twice.

create table if not exists public.protected_areas (
  id bigint generated by default as identity primary key,
  global_id text not null unique,
  objectid bigint,
  -- The government's site id from the data set. Not a sites_pa id.
  pasites_id bigint,
  -- Our site, set by the import when the name matches sites_pa.namesite. Null until matched.
  site_id bigint references public.sites_pa (id) on delete set null,
  name text not null,
  short_name text,
  oc_name text,
  area_type text not null,
  subtype text,
  status text,
  source text,
  iucn text,
  oc_no text,
  acres numeric,
  hectares numeric,
  oc_date date,
  date_est date,
  notes text,
  shape_area numeric,
  shape_length numeric,
  -- GeoJSON. The import wraps single Polygons as MultiPolygons.
  geometry jsonb not null,
  label_point jsonb,
  created_at timestamptz not null default now(),
  -- The import sets this on every refresh.
  updated_at timestamptz not null default now(),
  constraint protected_areas_geometry_type_check
    check (geometry ->> 'type' is not distinct from 'MultiPolygon'),
  constraint protected_areas_label_point_type_check
    check (label_point is null or label_point ->> 'type' = 'Point')
);

create index if not exists protected_areas_area_type_idx on public.protected_areas (area_type);
create index if not exists protected_areas_site_id_idx on public.protected_areas (site_id);

alter table public.protected_areas enable row level security;

-- Signed-in users read. Only the import (service role) writes.
revoke all on public.protected_areas from anon, authenticated;
grant select on public.protected_areas to authenticated;

drop policy if exists "Authenticated users can read protected areas" on public.protected_areas;
create policy "Authenticated users can read protected areas"
  on public.protected_areas for select to authenticated
  using (true);

notify pgrst, 'reload schema';
