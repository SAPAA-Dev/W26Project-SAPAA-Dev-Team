import { test } from 'node:test';
import assert from 'node:assert/strict';
import { schemaFromSql } from '../src/schema.mjs';
import { applyGenerated, begin, end } from '../src/markers.mjs';
import { erLines } from '../src/generate.mjs';
import { svgNames } from '../src/render.mjs';

const MIGRATIONS = [
  `create table public."W26_sites-pa" (id bigint generated by default as identity primary key, namesite text not null unique);
   create table public.areas (id bigint primary key, site_id bigint references public."W26_sites-pa" (id) on delete set null,
     global_id text unique, name text not null);
   create policy "p" on public.areas for select using (true);
   do $$ begin perform 1; end $$;`,
  `alter table if exists public."W26_sites-pa" rename to sites_pa;
   alter table public.areas drop column if exists site_id;
   alter table public.areas drop column if exists global_id;
   alter table public.areas add column if not exists folder text;
   alter table public.areas add column if not exists fid bigint;
   alter table public.areas alter column folder set not null;
   alter table public.areas add constraint areas_folder_fid_key unique (folder, fid);
   create table public.stewards (site_id bigint primary key references public."sites_pa" (id) on delete cascade,
     user_id uuid references auth.users (id));`,
];

test('replays migrations into the final schema', async () => {
  const s = await schemaFromSql(MIGRATIONS);
  assert.deepEqual([...s.tables.keys()], ['sites_pa', 'areas', 'stewards']);
  assert.deepEqual([...s.tables.get('areas').columns.keys()], ['id', 'name', 'folder', 'fid']);
  assert.equal(s.tables.get('areas').columns.get('folder').notNull, true);
  assert.deepEqual(s.tables.get('areas').uniques[0].cols, ['folder', 'fid']);
  assert.deepEqual(s.tables.get('stewards').columns.get('site_id').fk, { table: 'sites_pa', column: 'id', onDelete: 'cascade' });
  assert.equal(s.tables.get('stewards').columns.get('user_id').fk.table, 'auth.users');
  assert.deepEqual([...s.history.tables], ['W26_sites-pa']);
  assert.deepEqual([...s.history.columns], ['areas.site_id', 'areas.global_id']);
});

test('ER lines follow renames and skip dropped FKs', async () => {
  const s = await schemaFromSql(MIGRATIONS);
  const lines = erLines(s, { exclude: [], external: { 'auth.users': 'auth_users' }, categories: {}, notes: {} });
  assert.ok(lines.includes('sites_pa ||--o| stewards : "site_id"'));
  assert.ok(lines.includes('auth_users |o--o{ stewards : "user_id"'));
  assert.ok(!lines.some((l) => l.includes('areas : "site_id"')));
  assert.ok(lines.includes('    text folder "unique (folder, fid)"'));
});

const HAND = `classDiagram
    %% header comment, hand-written
    class Site {
        <<table sites_pa>>
        +id: number
        +namesite: string [CHANGE 2.0.3]
        +boundary: polygon [NEW 6.0.1]
        +folder: string [NEW 6.0.1]
    }
    class Old {
        <<new table areas, 6.0.1>>
        +name: string
    }
    class Plan {
        <<new 9.9.9>>
    }
    Site "1" --> "0..*" Plan : plans
    note for Site "kept"
`;
const GEN = ['class Site {', '    <<table sites_pa>>', '    +id: number', '    +namesite: string', '    +folder: string', '}'];

test('keeps hand-written text, removes proposed items that now exist, keeps tags', () => {
  const { text } = applyGenerated(HAND, 'models', GEN, 'class', new Set(['sites_pa', 'areas']));
  assert.ok(text.includes('%% header comment, hand-written'));
  assert.ok(text.includes(begin('models')) && text.includes(end('models')));
  assert.ok(text.includes('+namesite: string [CHANGE 2.0.3]'), 'CHANGE tag moves onto the generated line');
  assert.ok(text.includes('+boundary: polygon [NEW 6.0.1]'), 'proposed member stays');
  assert.ok(!text.includes('+folder: string [NEW 6.0.1]'), 'proposed member that now exists is removed');
  assert.ok(!text.includes('class Old'), '<<new table areas>> is removed because areas exists');
  assert.ok(text.includes('class Plan') && text.includes('note for Site "kept"'));
});

test('running twice gives the same file', () => {
  const once = applyGenerated(HAND, 'models', GEN, 'class', new Set(['areas'])).text;
  const twice = applyGenerated(once, 'models', GEN, 'class', new Set(['areas'])).text;
  assert.equal(twice, once);
});

test('maps each .mmd to the SVG that the design doc links', () => {
  const doc = '[Mermaid source](assets/ER_Diagram.mmd)\n\n![x](images/ER_Diagram_mermaid.svg)\n' +
    '[Mermaid source](assets/NoImage.mmd)\n[Mermaid source](assets/B.mmd)\n![b](images/B.svg)';
  const map = svgNames(doc);
  assert.equal(map.get('ER_Diagram.mmd'), 'ER_Diagram_mermaid.svg');
  assert.equal(map.get('B.mmd'), 'B.svg');
  assert.equal(map.has('NoImage.mmd'), false);
});
